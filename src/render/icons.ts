export type IconName = keyof typeof SPRITES;

const cache = new Map<IconName, string>();

export function icon(name: IconName): string {
  let svg = cache.get(name);
  if (!svg) {
    const rows = SPRITES[name];
    let path = '';
    rows.forEach((row, y) => {
      [...row].forEach((px, x) => {
        if (px === '#') path += `M${x} ${y}h1v1h-1z`;
      });
    });
    svg = `<svg class="px-icon icon-${name}" viewBox="0 0 ${rows[0].length} ${rows.length}" shape-rendering="crispEdges" fill="currentColor" aria-hidden="true"><path d="${path}"/></svg>`;
    cache.set(name, svg);
  }
  return svg;
}
